const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT_DIR = path.resolve(__dirname, '..');
const DEPLOY_DIR = path.join(ROOT_DIR, 'deploy');
const DEPLOY_WEB_DIR = path.join(DEPLOY_DIR, 'web');
const DEPLOY_API_DIR = path.join(DEPLOY_DIR, 'api');

console.log('🚀 Starting Standalone Production Packaging for IIS...');

// 1. Clean deploy directory
if (fs.existsSync(DEPLOY_DIR)) {
  console.log('🧹 Cleaning existing deploy/ directory...');
  fs.rmSync(DEPLOY_DIR, { recursive: true, force: true });
}
fs.mkdirSync(DEPLOY_WEB_DIR, { recursive: true });
fs.mkdirSync(DEPLOY_API_DIR, { recursive: true });

// 2. Package Web (Next.js Standalone)
console.log('📦 Assembling Standalone Web Application...');
const standaloneSrc = path.join(ROOT_DIR, 'apps/web/.next/standalone');
if (!fs.existsSync(standaloneSrc)) {
  throw new Error('apps/web/.next/standalone not found! Run "npm run build --workspace=@repo/web" first.');
}

// Copy standalone output
// Next.js monorepo standalone structure puts web code inside standalone/apps/web and root node_modules in standalone/node_modules
const standaloneWebSrc = path.join(standaloneSrc, 'apps/web');

// Copy server.js and files
fs.cpSync(standaloneWebSrc, DEPLOY_WEB_DIR, { recursive: true });

// Copy root node_modules from standalone into deploy/web/node_modules
const standaloneRootModules = path.join(standaloneSrc, 'node_modules');
if (fs.existsSync(standaloneRootModules)) {
  fs.cpSync(standaloneRootModules, path.join(DEPLOY_WEB_DIR, 'node_modules'), { recursive: true });
}

// Copy public assets
const webPublicSrc = path.join(ROOT_DIR, 'apps/web/public');
if (fs.existsSync(webPublicSrc)) {
  fs.cpSync(webPublicSrc, path.join(DEPLOY_WEB_DIR, 'public'), { recursive: true });
}

// Copy static assets (.next/static -> .next/static inside deploy/web)
const webStaticSrc = path.join(ROOT_DIR, 'apps/web/.next/static');
if (fs.existsSync(webStaticSrc)) {
  fs.cpSync(webStaticSrc, path.join(DEPLOY_WEB_DIR, '.next/static'), { recursive: true });
}

// Add IIS Reverse-Proxy web.config for Web
const webConfigWeb = `<?xml version="1.0" encoding="UTF-8"?>
<configuration>
    <system.webServer>
        <rewrite>
            <rules>
                <!-- 1. Route Swagger docs & Direct API calls (/api/v1/*) directly to NestJS (Port 3001) -->
                <rule name="DirectAPIToNestJS" stopProcessing="true">
                    <match url="^api/(v1/.*|docs.*)" />
                    <action type="Rewrite" url="http://127.0.0.1:3001/{R:0}" />
                </rule>

                <!-- 2. Route all other requests (Next.js web pages and Next.js /api proxy handler) to Next.js (Port 3000) -->
                <rule name="ReverseProxyToWeb" stopProcessing="true">
                    <match url="(.*)" />
                    <action type="Rewrite" url="http://127.0.0.1:3000/{R:1}" />
                </rule>
            </rules>
        </rewrite>
        <!-- Security & Protocol Headers -->
        <httpProtocol>
            <customHeaders>
                <add name="X-Forwarded-Proto" value="https" />
            </customHeaders>
        </httpProtocol>
    </system.webServer>
</configuration>
`;
fs.writeFileSync(path.join(DEPLOY_WEB_DIR, 'web.config'), webConfigWeb);

// Add Windows batch runner for Web
const startWebBat = `@echo off
echo Starting Crystal Martin Assets Web Portal...
set PORT=3000
set NODE_ENV=production
node server.js
pause
`;
fs.writeFileSync(path.join(DEPLOY_WEB_DIR, 'start-web.bat'), startWebBat);

// 3. Package API (NestJS)
console.log('📦 Assembling Standalone Backend API...');
const apiDistSrc = path.join(ROOT_DIR, 'apps/api/dist');
fs.cpSync(apiDistSrc, path.join(DEPLOY_API_DIR, 'dist'), { recursive: true });

// Fix relative require paths in deploy/api/dist generated by NestJS Swagger plugin
function fixRequiresInDir(dir) {
  const files = fs.readdirSync(dir);
  for (const f of files) {
    const full = path.join(dir, f);
    if (fs.statSync(full).isDirectory()) {
      fixRequiresInDir(full);
    } else if (f.endsWith('.js')) {
      let code = fs.readFileSync(full, 'utf8');
      if (code.includes('packages/types/dist/index')) {
        code = code.replace(/require\(["'][^"']*packages\/types\/dist\/index["']\)/g, 'require("@repo/types")');
        fs.writeFileSync(full, code);
      }
    }
  }
}
fixRequiresInDir(path.join(DEPLOY_API_DIR, 'dist'));

// Copy packages/types to relative path as a dual fallback
const deployPkgTypes = path.join(DEPLOY_DIR, 'packages/types/dist');
fs.mkdirSync(deployPkgTypes, { recursive: true });
fs.cpSync(path.join(ROOT_DIR, 'packages/types/dist'), deployPkgTypes, { recursive: true });

// Copy API package.json
fs.copyFileSync(path.join(ROOT_DIR, 'apps/api/package.json'), path.join(DEPLOY_API_DIR, 'package.json'));

// Copy Prisma schema and generated client with Windows engine
const prismaGeneratedSrc = path.join(ROOT_DIR, 'packages/database/generated/client');
const prismaDeployDest = path.join(DEPLOY_API_DIR, 'prisma-client');
fs.cpSync(prismaGeneratedSrc, prismaDeployDest, { recursive: true });

// Copy runtime production node_modules for API
console.log('📦 Resolving all transitive production dependencies for API...');
const apiModules = path.join(DEPLOY_API_DIR, 'node_modules');
fs.mkdirSync(apiModules, { recursive: true });

// Copy @repo packages into deploy/api/node_modules/@repo
const repoDest = path.join(apiModules, '@repo');
fs.mkdirSync(repoDest, { recursive: true });
fs.cpSync(path.join(ROOT_DIR, 'packages/types/dist'), path.join(repoDest, 'types/dist'), { recursive: true });
fs.copyFileSync(path.join(ROOT_DIR, 'packages/types/package.json'), path.join(repoDest, 'types/package.json'));

fs.cpSync(path.join(ROOT_DIR, 'packages/validators/dist'), path.join(repoDest, 'validators/dist'), { recursive: true });
fs.copyFileSync(path.join(ROOT_DIR, 'packages/validators/package.json'), path.join(repoDest, 'validators/package.json'));

// Link @repo/database to the Prisma client in deploy
const dbPkgDest = path.join(repoDest, 'database');
fs.mkdirSync(dbPkgDest, { recursive: true });
fs.cpSync(path.join(ROOT_DIR, 'packages/database/prisma'), path.join(dbPkgDest, 'prisma'), { recursive: true });
fs.cpSync(prismaGeneratedSrc, path.join(dbPkgDest, 'generated/client'), { recursive: true });
fs.copyFileSync(path.join(ROOT_DIR, 'packages/database/package.json'), path.join(dbPkgDest, 'package.json'));

// Recursively collect and copy all production dependencies using package-lock.json
const lockfilePath = path.join(ROOT_DIR, 'package-lock.json');
const pl = JSON.parse(fs.readFileSync(lockfilePath, 'utf8'));
const apiDeps = new Set();

function addPkgDeps(pkgKey) {
  const pkg = pl.packages[pkgKey];
  if (!pkg) return;
  const deps = Object.assign({}, pkg.dependencies, pkg.optionalDependencies);
  for (const [depName, version] of Object.entries(deps)) {
    if (depName.startsWith('@repo/')) continue;
    let resolvedKey = pkgKey + '/node_modules/' + depName;
    if (!pl.packages[resolvedKey]) {
      resolvedKey = 'node_modules/' + depName;
    }
    if (pl.packages[resolvedKey] && !apiDeps.has(depName)) {
      apiDeps.add(depName);
      addPkgDeps(resolvedKey);
    }
  }
}

addPkgDeps('apps/api');
addPkgDeps('packages/database');
addPkgDeps('packages/types');
addPkgDeps('packages/validators');

// Also scan any nested node_modules in node_modules itself
for (const [k, v] of Object.entries(pl.packages)) {
  if (k.startsWith('node_modules/')) {
    const topName = k.replace(/^node_modules\//, '').split('/node_modules/')[0];
    if (apiDeps.has(topName)) {
      // Add its dependencies too
      const deps = Object.assign({}, v.dependencies, v.optionalDependencies);
      for (const d of Object.keys(deps)) {
        if (!d.startsWith('@repo/')) {
          apiDeps.add(d);
        }
      }
    }
  }
}

// Guarantee critical runtime helpers are included
['tslib', '@prisma/client', 'dotenv', 'dotenv-expand', 'reflect-metadata', 'rxjs', 'process-nextick-args', 'core-util-is', 'isarray', 'util-deprecate', 'string_decoder', 'bcryptjs'].forEach(d => apiDeps.add(d));

console.log(`📦 Copying ${apiDeps.size} production modules into deploy/api/node_modules...`);
for (const mod of apiDeps) {
  const srcMod = path.join(ROOT_DIR, 'node_modules', mod);
  if (fs.existsSync(srcMod)) {
    const destMod = path.join(apiModules, mod);
    fs.mkdirSync(path.dirname(destMod), { recursive: true });
    fs.cpSync(srcMod, destMod, { recursive: true, dereference: true });
  }
}

// Add IIS web.config for API
const webConfigApi = `<?xml version="1.0" encoding="UTF-8"?>
<configuration>
    <system.webServer>
        <handlers>
            <add name="httpPlatformHandler" path="*" verb="*" modules="httpPlatformHandler" resourceType="Unspecified" />
        </handlers>
        <httpPlatform processPath="node.exe"
                      arguments="dist/main.js"
                      stdoutLogEnabled="true"
                      stdoutLogFile=".\\logs\\stdout"
                      startupTimeLimit="60">
            <environmentVariables>
                <environmentVariable name="PORT" value="%HTTP_PLATFORM_PORT%" />
                <environmentVariable name="API_PORT" value="%HTTP_PLATFORM_PORT%" />
                <environmentVariable name="NODE_ENV" value="production" />
            </environmentVariables>
        </httpPlatform>
    </system.webServer>
</configuration>
`;
fs.writeFileSync(path.join(DEPLOY_API_DIR, 'web.config'), webConfigApi);

// Copy .env template to deploy/api/.env
if (fs.existsSync(path.join(ROOT_DIR, '.env'))) {
  fs.copyFileSync(path.join(ROOT_DIR, '.env'), path.join(DEPLOY_API_DIR, '.env'));
}

// Add Windows batch runner for API
const startApiBat = `@echo off
echo Starting Crystal Martin Assets API Service...
set API_PORT=3001
set PORT=3001
set NODE_ENV=production
node dist/main.js
pause
`;
fs.writeFileSync(path.join(DEPLOY_API_DIR, 'start-api.bat'), startApiBat);

// Create uploads folder
fs.mkdirSync(path.join(DEPLOY_API_DIR, 'uploads'), { recursive: true });

// 4. Create deploy-iis.zip archive automatically
console.log('📦 Compressing deploy directory into deploy-iis.zip...');
try {
  const zipPath = path.join(ROOT_DIR, 'deploy-iis.zip');
  if (fs.existsSync(zipPath)) {
    fs.unlinkSync(zipPath);
  }
  execSync('zip -r -q -y deploy-iis.zip deploy', { cwd: ROOT_DIR });
  const sizeMb = (fs.statSync(zipPath).size / (1024 * 1024)).toFixed(2);
  console.log(`🗜️  Created deploy-iis.zip successfully (${sizeMb} MB)`);
} catch (err) {
  console.warn('⚠️  Could not create zip automatically:', err.message);
}

console.log('\\n✅ Standalone package successfully assembled at:');
console.log('   📁 ' + DEPLOY_DIR);
console.log('      ├── 📁 web/ (Self-contained Next.js server + all static assets)');
console.log('      └── 📁 api/ (Self-contained NestJS API + Prisma Windows engine)\\n');
console.log('🎉 This package requires ZERO npm install on the IIS server.');

